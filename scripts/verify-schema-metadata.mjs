import fs from 'node:fs';
import crypto from 'node:crypto';
const files = fs.readdirSync('supabase/migrations').filter(f=>f.endsWith('.sql')).sort();
const manifest = JSON.parse(fs.readFileSync('docs/generated/schema-manifest.json','utf8'));
const hashes = Object.fromEntries(files.map(f=>[f,crypto.createHash('sha256').update(Buffer.from(fs.readFileSync(`supabase/migrations/${f}`, 'utf8').replace(/\r\n/g, '\n'))).digest('hex')]));
const blob = Buffer.concat(files.map(f=>Buffer.from(fs.readFileSync(`supabase/migrations/${f}`, 'utf8').replace(/\r\n/g, '\n'))));
const hash = crypto.createHash('sha256').update(blob).digest('hex');
if (files.length !== manifest.migration_count) throw new Error(`Migration count drift: ${manifest.migration_count} != ${files.length}`);
if (hash !== manifest.schema_hash) throw new Error(`Schema hash drift: ${manifest.schema_hash} != ${hash}`);
for (const f of files) if (manifest.migration_hashes?.[f] !== hashes[f]) throw new Error(`Migration hash drift: ${f}`);
console.log(`SCHEMA METADATA: PASS (${files.length} migrations, hash ${hash})`);
