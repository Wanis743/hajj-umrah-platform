/**
 * The evidence gate.
 *
 * `scripts/certify.mjs` produces honest artifacts. This gate is what keeps them
 * honest afterwards, and it runs inside `verify:static` — no database, no
 * secrets, every commit. It exists because every single one of these was true in
 * this repository at 2e3fb0b:
 *
 *   - release/manifest.json said "certification": "VERIFIED" for 8 of 8 gates
 *     while release/evidence/evidence_rls_rbac.json said "status": "FAILED".
 *   - The evidence named commit 5680941, which `git rev-parse` cannot resolve —
 *     the artifacts described a tree that is not in this repository's history.
 *   - build-hash.txt contained BUILD_HASH_PLACEHOLDER and schema-hash.txt
 *     contained SCHEMA_HASH_PLACEHOLDER.
 *   - release/security-results/summary.txt asserted "BOLA/IDOR tests passed."
 *     in hand-typed prose, contradicting the evidence file for that same gate.
 *   - evidence_bola_idor.json cited `npm run verify:audit-privacy`, a script
 *     that has never existed in package.json.
 *
 * So the rules below are not stylistic. Each one is a specific way this
 * repository has already lied about its own test results:
 *
 *   1. A manifest must be machine-generated (it must name its generator).
 *   2. Its commit must be an object in this repository, and — when it claims
 *      VERIFIED — must be HEAD. A stale pass is not a pass.
 *   3. VERIFIED requires every gate VERIFIED. SKIPPED is not VERIFIED.
 *   4. No *_PLACEHOLDER anywhere under release/.
 *   5. Every referenced log must exist, and its recorded sha256 must match the
 *      bytes on disk, so evidence cannot be edited after the fact.
 *   6. Every command a manifest cites must resolve to a real npm script or file.
 *   7. No prose summary may assert a verdict. Machines report; files do not
 *      claim.
 *
 * An absent manifest is fine and is not a failure: uncertified is an honest
 * state. Claiming certification is the thing being policed.
 */
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const releaseDir = path.join(root, 'release');
const manifestPath = path.join(releaseDir, 'manifest.json');
const failures = [];
const notes = [];

/** Text of a file, transparently decoding the UTF-16 that some artifacts are in. */
function readText(file) {
  const bytes = fs.readFileSync(file);
  if (bytes[0] === 0xff && bytes[1] === 0xfe) return bytes.toString('utf16le');
  if (bytes[0] === 0xfe && bytes[1] === 0xff) return bytes.swap16().toString('utf16le');
  return bytes.toString('utf8');
}

function walk(dir) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else if (entry.isFile()) out.push(full);
  }
  return out;
}

const rel = (file) => path.relative(root, file).replaceAll(path.sep, '/');
const releaseFiles = walk(releaseDir);

// ── Rule 4: placeholders ───────────────────────────────────────────────────
// A placeholder in an evidence artifact is worse than an empty file: it occupies
// the slot where a measurement belongs and reads, at a glance, like one.
for (const file of releaseFiles) {
  if (file.endsWith('.json') && path.basename(file) === 'sbom.cdx.json') continue;
  const text = readText(file);
  const hit = text.match(/[A-Z_]*PLACEHOLDER[A-Z_]*|\bTODO\b|\bTBD\b|\bFIXME\b/);
  if (hit !== null) failures.push(`${rel(file)}: contains the placeholder \`${hit[0]}\` where a measured value belongs.`);
}

// ── Rule 7: prose files may not assert verdicts ─────────────────────────────
// These were hand-typed: "Security scans passed. BOLA/IDOR tests passed." next
// to an evidence file recording that same gate as FAILED.
const VERDICT_PROSE = /\b(passed|verified|successful|all tests pass|no vulnerabilities|certified)\b/i;
for (const file of releaseFiles) {
  if (!/\.(txt|md)$/.test(file)) continue;
  if (path.basename(file).startsWith('build-hash') || path.basename(file).startsWith('schema-hash')) continue;
  if (rel(file).startsWith('release/evidence/')) continue; // generated logs; their own tool's words
  const hit = readText(file).match(VERDICT_PROSE);
  if (hit !== null) {
    failures.push(
      `${rel(file)}: prose asserts a verdict (\`${hit[0]}\`). Evidence is generated by scripts/certify.mjs, not written; delete this file.`,
    );
  }
}

if (!fs.existsSync(manifestPath)) {
  notes.push('release/manifest.json is absent — this commit is uncertified, which is an honest state. Run `npm run certify` to produce one.');
} else {
  const raw = readText(manifestPath);
  let manifest = null;
  try {
    manifest = JSON.parse(raw);
  } catch (error) {
    failures.push(`release/manifest.json is not valid JSON: ${error.message}`);
  }

  if (manifest !== null) {
    const gates = Array.isArray(manifest.gates) ? manifest.gates : [];

    // ── Rule 1: generated, not typed ───────────────────────────────────────
    if (manifest.generator !== 'scripts/certify.mjs') {
      failures.push('release/manifest.json does not name scripts/certify.mjs as its generator; a hand-written manifest is a claim, not evidence.');
    }
    if (gates.length === 0) {
      failures.push('release/manifest.json lists no gates, so its verdict rests on nothing.');
    }

    // ── Rule 2: the commit must exist, and VERIFIED must mean HEAD ─────────
    const head = spawnSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).stdout.trim();
    const commit = manifest.commit ?? '';
    if (commit === '') {
      failures.push('release/manifest.json records no commit, so nothing ties its gates to a tree.');
    } else {
      const known = spawnSync('git', ['cat-file', '-e', `${commit}^{commit}`], { encoding: 'utf8' }).status === 0;
      if (!known) {
        failures.push(`release/manifest.json names commit ${commit}, which is not an object in this repository.`);
      } else if (manifest.certification === 'VERIFIED' && commit !== head) {
        failures.push(`release/manifest.json claims VERIFIED for ${commit.slice(0, 7)}, but HEAD is ${head.slice(0, 7)}. Gates must run against the current commit.`);
      } else if (commit !== head) {
        notes.push(`manifest is for ${commit.slice(0, 7)}, HEAD is ${head.slice(0, 7)} — re-run \`npm run certify\`.`);
      }
    }

    // ── Rule 3: VERIFIED requires every gate VERIFIED ──────────────────────
    // This is the whole of it. The old manifest's eight VERIFIED lines covered
    // gates whose own evidence said FAILED and whose summaries said "pending".
    const notVerified = gates.filter((gate) => gate.status !== 'VERIFIED');
    const absent = Array.isArray(manifest.absent_gates) ? manifest.absent_gates : [];
    if (manifest.certification === 'VERIFIED' && notVerified.length > 0) {
      failures.push(
        `release/manifest.json claims VERIFIED while ${notVerified.length} gate(s) are not: ${notVerified.map((gate) => `${gate.name}=${gate.status}`).join(', ')}.`,
      );
    }
    if (manifest.certification === 'VERIFIED' && absent.length > 0) {
      failures.push(`release/manifest.json claims VERIFIED while ${absent.length} demanded gate(s) are ABSENT: ${absent.map((gate) => gate.name).join(', ')}.`);
    }
    if (manifest.certification === 'VERIFIED' && manifest.working_tree !== 'CLEAN') {
      failures.push(
        `release/manifest.json claims VERIFIED but records working_tree=${JSON.stringify(manifest.working_tree)}; only a clean tree proves the bytes tested were the bytes of the named commit.`,
      );
    }
    for (const gate of gates) {
      if (!['VERIFIED', 'FAILED', 'SKIPPED'].includes(gate.status)) {
        failures.push(`release/manifest.json gate \`${gate.name}\` has the unrecognised status \`${gate.status}\`.`);
      }
      if (gate.status === 'VERIFIED' && gate.exit_code !== 0) {
        failures.push(`release/manifest.json gate \`${gate.name}\` is VERIFIED but recorded exit code ${gate.exit_code}.`);
      }
    }

    // ── Rule 5: logs must exist and match their recorded hash ──────────────
    for (const gate of gates) {
      if (gate.log === undefined) {
        if (gate.status !== 'SKIPPED') failures.push(`release/manifest.json gate \`${gate.name}\` is ${gate.status} but cites no log.`);
        continue;
      }
      const logPath = path.join(releaseDir, gate.log);
      if (!fs.existsSync(logPath)) {
        failures.push(`release/manifest.json gate \`${gate.name}\` cites release/${gate.log}, which does not exist.`);
        continue;
      }
      const actual = crypto.createHash('sha256').update(fs.readFileSync(logPath)).digest('hex');
      if (gate.log_sha256 !== actual) {
        failures.push(`release/${gate.log} has been modified since it was recorded (sha256 ${actual.slice(0, 12)}… ≠ ${String(gate.log_sha256).slice(0, 12)}…).`);
      }
    }

    // ── Rule 6: every cited command must resolve ───────────────────────────
    // evidence_bola_idor.json cited `npm run verify:audit-privacy`, which has
    // never existed. A gate pointing at nothing cannot have run.
    const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
    for (const gate of gates) {
      const command = gate.command ?? '';
      const scriptName = command.match(/^npm run ([\w:-]+)/)?.[1];
      if (scriptName !== undefined && pkg.scripts?.[scriptName] === undefined) {
        failures.push(`release/manifest.json gate \`${gate.name}\` cites \`npm run ${scriptName}\`, which is not a script in package.json.`);
      }
      const scriptFile = command.match(/(?:node|bash)\s+(?:--[\w=-]+\s+)*([\w./-]+\.(?:mjs|js|cjs|sh))/)?.[1];
      if (scriptFile !== undefined && !fs.existsSync(path.join(root, scriptFile))) {
        failures.push(`release/manifest.json gate \`${gate.name}\` cites ${scriptFile}, which does not exist.`);
      }
    }

    // ── Hashes must be measurements ────────────────────────────────────────
    for (const [field, tree] of [['build_hash', 'dist/'], ['schema_hash', 'supabase/migrations/']]) {
      const value = manifest[field];
      if (manifest.certification === 'VERIFIED' && !/^[0-9a-f]{64}$/.test(String(value))) {
        failures.push(`release/manifest.json claims VERIFIED but ${field} is \`${value}\` rather than a sha256 over ${tree}.`);
      }
    }

    // ── No orphaned evidence ───────────────────────────────────────────────
    // The old release/evidence/ held ten evidence_*.json + raw_log_*.txt pairs
    // that no live gate produced or referenced, describing runs from another
    // checkout. Unreferenced evidence gets read as though it were current.
    const cited = new Set(gates.filter((gate) => gate.log !== undefined).map((gate) => path.basename(gate.log)));
    for (const file of walk(path.join(releaseDir, 'evidence'))) {
      if (!cited.has(path.basename(file))) {
        failures.push(`${rel(file)} is not referenced by any gate in release/manifest.json; stale evidence reads as current evidence.`);
      }
    }
  }
}

if (failures.length > 0) {
  console.error('EVIDENCE GATE FAIL');
  for (const failure of failures) console.error(`- ${failure}`);
  console.error('\nEvidence is produced by `npm run certify` and must not be edited. Delete a false artifact rather than correcting its wording:');
  console.error('an absent manifest means uncertified, which is true and checkable; a hand-written one means nothing at all.');
  process.exit(1);
}
console.log(`EVIDENCE GATE PASS (${releaseFiles.length} artifact${releaseFiles.length === 1 ? '' : 's'} under release/ checked)`);
for (const note of notes) console.log(`  note: ${note}`);
