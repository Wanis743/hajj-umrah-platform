import { randomUUID } from 'node:crypto';
const enabled = process.env.LOAD_TEST_ENABLE === '1';
if (!enabled) throw new Error('Reservation concurrency certification cannot be skipped. Set LOAD_TEST_ENABLE=1 in staging.');
if (process.env.LOAD_TEST_ENV !== 'staging') throw new Error('Refusing concurrency test unless LOAD_TEST_ENV=staging.');
const base = process.env.E2E_BASE_URL;
const packageId = process.env.TEST_PACKAGE_ID;
const turnstile = process.env.TEST_TURNSTILE_TOKEN;
if (!base || !packageId || !turnstile) throw new Error('E2E_BASE_URL, TEST_PACKAGE_ID and TEST_TURNSTILE_TOKEN are required.');
const requests = Number(process.env.TEST_REQUESTS || 100);
const capacityBefore = Number(process.env.TEST_CAPACITY_BEFORE);
if (!Number.isInteger(capacityBefore) || capacityBefore < 1) throw new Error('TEST_CAPACITY_BEFORE must be a positive integer fixture value.');
const idempotency = randomUUID();
const payload = { name:'CERTIFICATION TEST', phone:'+213500000000', email:'certification@example.invalid', package_id:packageId, start_date:process.env.TEST_START_DATE, end_date:process.env.TEST_END_DATE, travelers:1, notes:'staging certification' };
const endpoint = `${base.replace(/\/$/,'')}/functions/v1/create-reservation`;
const responses = await Promise.all(Array.from({length:requests}, () => fetch(endpoint,{method:'POST',headers:{'content-type':'application/json','origin':base,'idempotency-key':idempotency,'x-turnstile-token':turnstile},body:JSON.stringify(payload)})));
const bodies = await Promise.all(responses.map(async r => ({status:r.status, body:await r.json().catch(()=>({}))})));
const accepted = bodies.filter(x => x.status >= 200 && x.status < 300);
const deduped = accepted.filter(x => x.body?.deduplicated === true);
if (accepted.length !== 1) throw new Error(`Idempotency invariant failed: expected exactly 1 created response, got ${accepted.length}.`);
if (!accepted[0].body?.reference) throw new Error('Accepted reservation did not return a reference.');
if (deduped.length !== 0) throw new Error('First response unexpectedly marked deduplicated.');
console.log(JSON.stringify({pass:true,requests,created:1,retries:requests-1,idempotency:'exactly-one',capacityBefore},null,2));
