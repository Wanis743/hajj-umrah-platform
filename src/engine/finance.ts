export function calculateRevenuePerPilgrim(bookings: Array<{ total_dzd?: number | null; amount_dzd?: number | null; }>) {
  if (bookings.length === 0) return 0;
  const totalRevenue = bookings.reduce((sum, b) => sum + Number(b.total_dzd ?? b.amount_dzd ?? 0), 0);
  return totalRevenue / bookings.length;
}
