export type ProfitabilityAnalysis = {
  totalRevenue: number;
  totalExpenses: number;
  netProfit: number;
  marginPercentage: number;
};

export type FinancialSummary = {
  period: string;
  totalRevenueDZD: number;
  totalRevenueSAR: number;
  expensesDZD: number;
  expensesSAR: number;
};

type AmountLike = { amount?: number | null; amount_dzd?: number | null };

export function calculateProfitability(_bookings: unknown[], payments: AmountLike[], expenses: AmountLike[]): ProfitabilityAnalysis {
  const totalRevenue = payments.reduce((sum, p) => sum + Number(p.amount ?? p.amount_dzd ?? 0), 0);
  const totalExpenses = expenses.reduce((sum, e) => sum + Number(e.amount ?? e.amount_dzd ?? 0), 0);
  const netProfit = totalRevenue - totalExpenses;
  return { totalRevenue, totalExpenses, netProfit, marginPercentage: totalRevenue > 0 ? (netProfit / totalRevenue) * 100 : 0 };
}

